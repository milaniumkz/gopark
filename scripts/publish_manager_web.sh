#!/usr/bin/env bash
# Publish only the matching, tested brigadier web bundle. No service restart.
set -euo pipefail
: "${CODE_SHA:?}" "${WEB_SHA256:?}" "${STAGE:?}"
[[ "$CODE_SHA" =~ ^[0-9a-f]{40}$ ]]
[[ "$WEB_SHA256" =~ ^[0-9a-f]{64}$ ]]
BASE=${GOPARK_DEPLOY_BASE:-/home/client}
exec 9>/tmp/gopark-production-deploy.lock
flock -n 9 || { echo 'Another deploy is running'; exit 1; }
test "$(cat "$BASE/gopark-current-sha")" = "$CODE_SHA"
CURRENT=$(readlink -f "$BASE/gopark-current")
WEB_DIR="$CURRENT/apps/manager-app/build/web"
BACKUP="$BASE/backups/manager-web-$CODE_SHA-$(date -u +%Y%m%dT%H%M%SZ)"
RUNTIME_TOKEN="${CODE_SHA}-$(date -u +%s%N)"
cd "$STAGE"
printf '%s  manager-web.tar.gz\n' "$WEB_SHA256" | sha256sum --check
# All files are generated by Flutter; reject unexpected archive paths.
if tar -tzf manager-web.tar.gz | grep -Eq '(^/|(^|/)\.\.(/|$))'; then echo 'Invalid bundle paths'; exit 1; fi
mkdir -p web-verified
tar -xzf manager-web.tar.gz -C web-verified
find web-verified -type d -exec chmod 755 {} +
find web-verified -type f -exec chmod 644 {} +
test -s web-verified/index.html
test -s web-verified/flutter_bootstrap.js
test -s web-verified/main.dart.js
grep -q '<base href="/manager/">' web-verified/index.html
curl --max-time 15 -fsS http://127.0.0.1:3000/api/health >/dev/null
mkdir -p "$BACKUP/runtime"
chmod 700 "$BACKUP"
if [ -d "$WEB_DIR" ]; then cp -a "$WEB_DIR" "$BACKUP/persistent"; fi
docker cp gopark-crm-web:/usr/share/nginx/html/manager/. "$BACKUP/runtime/"
rollback() {
  result=$?
  trap - ERR
  echo 'Restoring previous brigadier web files.'
  rm -rf "$WEB_DIR"
  if [ -d "$BACKUP/persistent" ]; then cp -a "$BACKUP/persistent" "$WEB_DIR"; fi
  docker exec gopark-crm-web rm -rf /usr/share/nginx/html/manager
  docker exec gopark-crm-web mkdir -p /usr/share/nginx/html/manager
  docker cp "$BACKUP/runtime/." gopark-crm-web:/usr/share/nginx/html/manager/
  exit "$result"
}
trap rollback ERR
mkdir -p "$(dirname "$WEB_DIR")"
cp -a web-verified "$WEB_DIR.new"
if [ -d "$WEB_DIR" ]; then mv "$WEB_DIR" "$BACKUP/previous-directory"; fi
mv "$WEB_DIR.new" "$WEB_DIR"
docker exec gopark-crm-web mkdir -p "/usr/share/nginx/html/.manager.new-$RUNTIME_TOKEN"
docker cp "$WEB_DIR/." "gopark-crm-web:/usr/share/nginx/html/.manager.new-$RUNTIME_TOKEN/"
docker exec gopark-crm-web mv /usr/share/nginx/html/manager "/usr/share/nginx/html/.manager.previous-$RUNTIME_TOKEN"
docker exec gopark-crm-web mv "/usr/share/nginx/html/.manager.new-$RUNTIME_TOKEN" /usr/share/nginx/html/manager
expected=$(sha256sum web-verified/main.dart.js | cut -d' ' -f1)
actual=$(docker exec gopark-crm-web sha256sum /usr/share/nginx/html/manager/main.dart.js | cut -d' ' -f1)
test "$actual" = "$expected"
curl --max-time 15 -fsS http://127.0.0.1:3000/manager/ | grep -q '<base href="/manager/">'
curl --max-time 15 -fsS http://127.0.0.1:3000/api/health >/dev/null
trap - ERR
docker exec gopark-crm-web rm -rf "/usr/share/nginx/html/.manager.previous-$RUNTIME_TOKEN"
printf 'Published brigadier web %s; backup: %s\n' "$CODE_SHA" "$BACKUP"
